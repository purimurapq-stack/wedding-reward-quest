import {writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {allowedUsers} from '../src/firebase-config.js';
import {initial,recoveryEvents,eventEffect,quests,statusPrompts} from '../src/data.js';
const literal=JSON.stringify;
function ruleTime(at){const d=new Date(at),s=d.getUTCHours()*3600+d.getUTCMinutes()*60+d.getUTCSeconds();return `timestamp.date(${d.getUTCFullYear()}, ${d.getUTCMonth()+1}, ${d.getUTCDate()}) + duration.value(${s}, 's')`;}
export function buildRules(users=allowedUsers){
 const keys=['hp','mp','hunger','joy'];
 const rewardGroups=new Map();
 for(const e of recoveryEvents){
  const reward=eventEffect(e);
  const players=Object.fromEntries(['groom','bride'].map(role=>[role,Object.fromEntries(keys.map(key=>{
   const max=reward.max[key]||0,recovery=reward.current[key]||0;
   const base=`before.players.${role}.${key}`;
   return [key,max===0&&recovery===0?base:`[clamp(${base}[0] + (${recovery}), ${base}[1] + ${max}), ${base}[1] + ${max}]`];
  }))]));
  const expected='{'+Object.entries(players).map(([role,stats])=>`${literal(role)}:{`+Object.entries(stats).map(([key,value])=>`${literal(key)}:${value}`).join(',')+'}').join(',')+'}';
  const prefix=e.id.split('-')[0];if(!rewardGroups.has(prefix))rewardGroups.set(prefix,[]);
  rewardGroups.get(prefix).push(`id == '${e.id}' ? (request.time >= ${ruleTime(e.availableAt)} && after.players == ${expected}) :`);
 }
 const events=[...rewardGroups].map(([prefix,branches])=>`id.matches('^${prefix}-.*') ? (${branches.join('\n        ')} false) :`).join('\n        ');
 const integerBounds=['groom','bride'].flatMap(role=>keys.map(key=>`p.${role}.${key}[0] is int && p.${role}.${key}[1] is int && p.${role}.${key}[1] > 0 && p.${role}.${key}[1] <= 10000`)).join('\n        && ');
 const questTimes=quests.map(q=>`'${q.id}': ${ruleTime(q.revealAt)}`).join(',\n        ');
 const nights=statusPrompts.map(p=>`'${p.date}': ${ruleTime(p.at)}`).join(',\n        ');
 return `// Generated by npm run rules:generate. Deploy only after reviewing both UIDs.
rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function groomUID() { return ${literal(users.groom)}; }
    function brideUID() { return ${literal(users.bride)}; }
    function allowed() {
      return request.auth != null && groomUID() != '' && brideUID() != '' && groomUID() != brideUID()
        && request.auth.token.firebase.sign_in_provider == 'google.com'
        && request.auth.uid in [groomUID(), brideUID()];
    }
    function owner() { return request.auth.uid == groomUID() ? 'groom' : 'bride'; }
    function other() { return owner() == 'groom' ? 'bride' : 'groom'; }
    function pair(p) {
      return p is list && p.size() == 2 && p[0] is int && p[1] is int
        && p[1] > 0 && p[1] <= 10000 && p[0] >= 0 && p[0] <= p[1];
    }
    function player(p) {
      return p is map && p.size() == 4 && p.keys().hasOnly(['hp','mp','hunger','joy'])
        && pair(p.hp) && pair(p.mp) && pair(p.hunger) && pair(p.joy);
    }
    // Each operation validates player values once: exact init/reward, unchanged quest, or owner-only status.
    function envelope(d) {
      return d.size() == 8
        && d.keys().hasOnly(['schemaVersion','players','done','questClears','logs','revision','lastOperation','updatedAt'])
        && d.schemaVersion == 1 && d.revision is int && d.revision >= 0 && d.revision <= 100000
        && d.players is map && d.players.size() == 2 && d.players.keys().hasOnly(['groom','bride'])
        && d.done is list && d.done.size() <= ${recoveryEvents.length}
        && d.questClears is map && d.questClears.size() <= ${quests.length}
        && d.logs is map && d.logs.size() <= 6
        && d.lastOperation is map && d.lastOperation.actor == request.auth.uid && d.updatedAt == request.time;
    }
    function validReward(before, after, id) {
      // Select a branch first. Only literal numeric vectors reach repeated stat comparisons.
      return ${events}
        false;
    }
    function questTable() {
      return {${questTimes}};
    }
    function nightTable() { return {${nights}}; }
    function clamp(v, max) { return v < 0 ? 0 : (v > max ? max : v); }
    function computedPlayerBounds(p) {
      return ${integerBounds};
    }
    function validEvent(before, after, op) {
      return op.keys().hasOnly(['kind','id','actor']) && op.id is string && op.id in ${literal(recoveryEvents.map(e=>e.id))}
        && !(op.id in before.done)
        && after.done == before.done.concat([op.id]) && after.questClears == before.questClears && after.logs == before.logs
        && computedPlayerBounds(after.players) && validReward(before, after, op.id);
    }
    function validQuest(before, after, op) {
      return op.keys().hasOnly(['kind','id','actor']) && op.id is string && questTable().keys().hasAny([op.id])
        && request.time >= questTable()[op.id] && !(op.id in before.questClears)
        && after.questClears.diff(before.questClears).affectedKeys().hasOnly([op.id])
        && after.questClears[op.id] == request.time
        && after.players == before.players && after.done == before.done && after.logs == before.logs;
    }
    function sameMax(before, after) {
      return after.hp[1] == before.hp[1] && after.mp[1] == before.mp[1]
        && after.hunger[1] == before.hunger[1] && after.joy[1] == before.joy[1];
    }
    function validStatus(before, after, op) {
      return op.keys().hasOnly(['kind','date','player','actor']) && op.player == owner()
        && op.date is string && nightTable().keys().hasAny([op.date]) && request.time >= nightTable()[op.date]
        && after.done == before.done && after.questClears == before.questClears
        && after.players[other()] == before.players[other()] && player(after.players[owner()]) && sameMax(before.players[owner()], after.players[owner()])
        && after.logs.diff(before.logs).affectedKeys().hasOnly([op.date + ':' + owner()])
        && after.logs[op.date + ':' + owner()] == {'hp':after.players[owner()].hp[0], 'mp':after.players[owner()].mp[0], 'hunger':after.players[owner()].hunger[0], 'joy':after.players[owner()].joy[0]};
    }
    match /couples/wedding-2026 {
      allow get: if allowed();
      allow list, delete: if false;
      allow create: if allowed() && envelope(request.resource.data)
        && request.resource.data.revision == 0 && request.resource.data.players == ${literal(initial)}
        && request.resource.data.done == [] && request.resource.data.questClears == {} && request.resource.data.logs == {}
        && request.resource.data.lastOperation == {'kind':'init','actor':request.auth.uid};
      allow update: if allowed() && envelope(request.resource.data)
        && request.resource.data.revision == resource.data.revision + 1
        && ((request.resource.data.lastOperation.kind == 'event' && validEvent(resource.data, request.resource.data, request.resource.data.lastOperation))
         || (request.resource.data.lastOperation.kind == 'quest' && validQuest(resource.data, request.resource.data, request.resource.data.lastOperation))
         || (request.resource.data.lastOperation.kind == 'status' && validStatus(resource.data, request.resource.data, request.resource.data.lastOperation)));
    }
    match /{document=**} { allow read, write: if false; }
  }
}
`;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){await writeFile('firestore.rules',buildRules());console.log('firestore.rules generated. Empty UIDs deny all access. No deploy was performed.');}
